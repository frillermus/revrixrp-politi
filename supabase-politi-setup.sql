-- RevrixRP politihåndbog: databaseindhold, rangorden og adgangspolitikker.
-- Kør hele filen i Supabase Dashboard -> SQL Editor i det eksisterende projekt.
-- Login benytter Supabase Auth-konti fra den tilknyttede RevrixRP-løsning.

create table if not exists public.police_handbook_sections (
  id text primary key,
  category text not null,
  title text not null,
  summary text not null default '',
  content jsonb not null default '[]'::jsonb check (jsonb_typeof(content) = 'array'),
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.police_ranks (
  id text primary key,
  code text not null,
  name text not null default '',
  rank text not null,
  district text not null default '',
  permissions jsonb not null default '[]'::jsonb check (jsonb_typeof(permissions) = 'array'),
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);

alter table public.police_handbook_sections enable row level security;
alter table public.police_ranks enable row level security;
grant select on public.police_handbook_sections to authenticated;
grant select on public.police_ranks to authenticated;

drop policy if exists "Signed-in users can read police handbook" on public.police_handbook_sections;
create policy "Signed-in users can read police handbook" on public.police_handbook_sections
  for select to authenticated using (true);
drop policy if exists "Signed-in users can read police ranks" on public.police_ranks;
create policy "Signed-in users can read police ranks" on public.police_ranks
  for select to authenticated using (true);

